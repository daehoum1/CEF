"""Review round 3, comment 4: does concept evidence help where class names are weakly
grounded, outside painting?

Repeats the Oxford-IIIT Pet probe protocol (pets_arm.py: four backbones, five-template
prompt ensemble, pretrained logit scale, 20:80 class-stratified image-level resplit,
five seeds, identical grids, staged search with the ZLaP candidate, bAcc selection)
on three more domains chosen to span class-name grounding:

  dtd       Describable Textures, 47 classes, 5,640 images
  eurosat   EuroSAT RGB land cover, 10 classes, 27,000 images
  aircraft  FGVC-Aircraft variants, 100 classes, 10,000 images (bottom banner cropped)
  pets_s5   Oxford-IIIT Pet again, with a dictionary regenerated by Claude Sonnet 5 so
            that every probe dictionary comes from the same model as the style ones

Dictionaries are generated per class by headless Claude Sonnet 5 (the route of
r3_generate_dicts.py) with the Pet prompt structure and domain axes. Every prompt bans
the class name, direct synonyms and proper names; phrases containing a class-name stem
or a capitalised possessive are re-queried.

  --stage gen      assets/r3_dicts/probe_{domain}.json (+ raw attempts)
  --stage encode   analysis/r3_probe_cache/{domain}_{tag}.npz
  --stage eval     results/supplementary/round3/probe_per_seed.csv
"""
